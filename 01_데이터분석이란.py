# 분석의 대부분이 이 모양입니다. - 나누고, 재고, 비교한다
# 같은 계산을 배치마다 세 번 해야 하나, 함수로 만들어 둡니다. 추후 빠른 수정을 위해 복붙보다는 함수를 써야한다.


def stat(value):
    """
    숫자 리스트를 받아 개수, 평균, 최대, 최소, 범위, 흔들림을 딕셔너리로 돌려줍니다.
    왜 딕셔너리로 돌려주나 - 값 여섯 개를 튜플로 돌려주면 받는 쪽에서 순서를 기억해야 합니다.
    s[3]이 최소인지 범위인지 사흘 뒤엔 모릅니다.
    딕셔너리면 s["최소"]라고 쓰게 되어 코드가 스스로 설명합니다.
    """
    count = len(value)
    avg = round(sum(value) / len(value), 2)
    top = max(value)
    low = min(value)
    span = round(top - low, 2)
    gaps = [
        abs(t - avg) for t in value
    ]  # t에서 평균(avg)을 빼서 절댓값(abs)을 씌운다. 근데 이때 t는 value라는 list를 에서 가져온다. list내 모든 값에 대해 진행할 것이다.
    spread = round(
        sum(gaps) / len(gaps), 2
    )  # round를 통해 2자리까지만 답을 얻는다. 그 값은 sum과 len값의 나눈 것이고 sum은 gaps의 합, len은 gaps의 리스트 길이.
    return {
        "개수": count,
        "평균": avg,
        "최대": top,
        "최소": low,
        "범위": span,
        "흔들림": spread,
    }  # return은 앞서 구한 count, avg, top, low, span, spread를 딕셔너리로 반환한다.


