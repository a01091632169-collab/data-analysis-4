# 3. 무엇을 맞히려는 건가 - 정답 칸의 생김새가 문제를 정함
# =================
# 분석을 시작할 때 가장 먼저 정하는건 도구가 아님. "무엇을 맞히는가" 이다
# 이게 안 정해지면 어떤 코드를 써야 할지도 안 정해짐.

# 현장에서 자주 만나는 문제는 크게 네 가지
# 무엇을 묻나                    정답의 생김새           문제의 이름
# 이 설비가 고장 날까?             예 / 아니오              분류
# 이번에 만든 제품이 불량일까?     불량 / 양품               분류
# 이 조건이면 강도가 얼마나 나올까  숫자(예:320MPa)          회귀
# 지금 뭔가 평소랑 다른가?         정답 칸이 아예 없음     이상 탐지

# 판단 기준은 세 줄
# 정답이 칸막이(몇 가지 중 하나)면 -> 분류
# 정답이 연속된 숫자면 -> 회귀
# 정답 칸이 아예 없으면 -> 이상 탐지

# *비유* 문제집 뒤에 붙어 있는 답지를 생각해 보기.
# 답지가 있으면 내가 푼 걸 맞혔는지 틀렸는지 알 수 있고, 틀린 데서 배움
# 답지가 없으면 채점을 못 함. 문제를 못 푸는 게 아니라 채점이 안 되는 것
# 라벨이 그 답지. 모델은 답지를 보고 배움.
# 설비 라벨은 사람이 손으로 적음. 빠트릴 수도 있고 틀릴 수도 있음
# 우리가 아래에 하는 것들 중 "숫자로는 제일 수상한데 라벨은 정상"인 줄을 한 줄 만남
# 답지를 의심해야 하는 순간이 실제로 있다는 뜻.

# 라벨(label) = 정답 칸. 품질검사 결과처럼 "이건 불량이었다"를 적어둔 열
# 모델은 이 칸을 보고 배움. 그래서 라벨이 없으면 분류 회귀를 아예 못함

# 왜 이 구분이 "분석의 첫 단추" 인가
# 종류가 정해지면 뒤의 거의 모든 게 다라서 정해짐.
# 쓸 수 있는 모델도, 잘됐는지 재는 방법도 다름.
# 분류는 "몇 개 맞혔나"로 재고, 회귀는 "얼마나 빗나갔나"로 잼.
# 이걸 섞으면 계산은 돌아가는데 겨로가가 아무 뜻이 없어짐.
# 그래서 코드를 한 줄쓰기 전에 "내 정답 칸이 어느 쪽인가"를 먼저 봄.

# 같은 파일인데 어느 칸을 정답으로 삼느냐에 따라 분류 문제도 되고 회귀 문제도 됨.
