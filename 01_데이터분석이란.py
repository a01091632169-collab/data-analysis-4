import csv  # csv 파일을 줄 칸으로 끊어 읽어 주는 파이썬 기본 모듈
import os  # 파일 경로를 다루는 파이썬 기본 모듈


def dp(name):
    """실행 위치가 어디든 data 폴더를 찾아 주는 작은 도우미 함수
    data/17_열처리.csv"지금있는 폴더 아래의 data를 뜻함
    그래서 터미널이 어느 폴더에 서 있느냐에 따라 같은 코드가 되기도 하고
    FileNotFindError가 나기도 한다
    폴더 배치 data-analysis-4/data 밑에 있음
    """
    here = os.path.dirname(os.path.abspath(__file__))
    for c in (
        os.path.join("data", name),
        os.path.join(here, "data", name),
        os.path.join(here, "..", "data", name),
    ):
        if os.path.exists(c):
            return c
    return os.path.join("data", name)


### __file__ 은 지금 있는 .py의 파일 경로 /  os.path.abspath(__file__) 은 그 경로를 절대경로로 바꿈
###   os.path.dirname(...) → 경로에서 파일 이름을 빼고 폴더 경로만 가져옴


